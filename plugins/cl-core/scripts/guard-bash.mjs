#!/usr/bin/env node
// PreToolUse hook for Bash and PowerShell: a tripwire for common destructive accidents, not a sandbox.
// It catches the usual forms of recursive deletes outside build folders, force pushes, and commands
// that throw away uncommitted work. Variables, aliases you define, scripts written to disk and then
// run, other interpreters, and deliberate obfuscation all get past it. The stronger layer is
// permissions.deny in .claude/settings.json (see hooks/README.md); keep both.
// Reads the hook payload from stdin. Exit 2 blocks the call and shows the message; an unreadable
// payload also blocks, so a broken hook is visible instead of silently off.
import { posix } from "node:path";

// Folders a recursive delete may target: regenerated by tools, never hand-written.
const SAFE_DIRS = new Set(["node_modules", "dist", "build", "out", ".cache"]);
const SHELL_KEYWORDS = new Set(["if", "then", "else", "elif", "do", "while", "until", "!", "time"]);
const PS_PARAMS = ["recurse", "force", "path", "literalpath", "filter", "include", "exclude", "credential", "stream", "confirm", "whatif", "verbose", "debug", "erroraction", "errorvariable", "warningaction", "warningvariable", "informationaction", "informationvariable", "outvariable", "outbuffer", "pipelinevariable", "progressaction"];
const PS_VALUED = new Set(["filter", "include", "exclude", "credential", "stream", "erroraction", "errorvariable", "warningaction", "warningvariable", "informationaction", "informationvariable", "outvariable", "outbuffer", "pipelinevariable", "progressaction"]);
const DELETE_CMDS = new Set(["rm", "remove-item", "ri", "del", "erase", "rd", "rmdir"]);
const CMD_STYLE = new Set(["del", "erase", "rd", "rmdir"]);

// Reads a $( ... ) body starting after the opening paren; returns [body, index of closing paren].
function readParen(src, start) {
  let depth = 1, i = start;
  for (; i < src.length; i++) {
    if (src[i] === "(") depth++;
    else if (src[i] === ")" && --depth === 0) break;
  }
  return [src.slice(start, i), i];
}

// Splits a command line into words and operators. Handles single and double quotes, the shell's
// escape character, $( ) and backtick substitutions (returned as nested sources), and redirections.
function tokenize(src, shell = "bash") {
  const esc = shell === "powershell" ? "`" : shell === "cmd" ? "^" : "\\";
  const tokens = [], nested = [];
  let word = null, quoted = false;
  const push = () => { if (word !== null) tokens.push({ w: word, q: quoted }); word = null; quoted = false; };
  const add = (s) => { word = (word ?? "") + s; };
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (c === esc && i + 1 < src.length) { i++; if (src[i] !== "\n") add(src[i]); quoted = true; continue; }
    if (c === "'" && shell !== "cmd") {
      const j = src.indexOf("'", i + 1), end = j === -1 ? src.length : j;
      add(src.slice(i + 1, end)); quoted = true; i = end; continue;
    }
    if (c === '"') {
      add(""); quoted = true;
      for (i++; i < src.length && src[i] !== '"'; i++) {
        if (src[i] === esc && shell !== "cmd" && i + 1 < src.length) { add(src[++i]); continue; }
        if (src[i] === "$" && src[i + 1] === "(" && shell !== "cmd") { const [body, end] = readParen(src, i + 2); nested.push(body); add("$(...)"); i = end; continue; }
        if (src[i] === "`" && shell === "bash") { const j = src.indexOf("`", i + 1), end = j === -1 ? src.length : j; nested.push(src.slice(i + 1, end)); add("$(...)"); i = end; continue; }
        add(src[i]);
      }
      continue;
    }
    if (c === "$" && src[i + 1] === "(" && shell !== "cmd") { const [body, end] = readParen(src, i + 2); nested.push(body); add("$(...)"); i = end; continue; }
    if (c === "$" && src[i + 1] === "{") { const j = src.indexOf("}", i), end = j === -1 ? src.length : j; add(src.slice(i, end + 1)); i = end; continue; }
    if (c === "`" && shell === "bash") { const j = src.indexOf("`", i + 1), end = j === -1 ? src.length : j; nested.push(src.slice(i + 1, end)); add("$(...)"); i = end; continue; }
    if (c === "\n" || c === ";" || c === "(" || c === ")") { push(); tokens.push({ op: c }); continue; }
    if (/\s/.test(c)) { push(); continue; }
    if (c === ">" || c === "<") {
      if (word !== null && !quoted && /^\d+$/.test(word)) { word = null; quoted = false; } else push(); // 2> drops the fd number
      while (i + 1 < src.length && /[<>&|]/.test(src[i + 1])) i++;
      tokens.push({ op: "redir" }); continue;
    }
    if (c === "&" && src[i + 1] === ">") { push(); i++; while (src[i + 1] === ">") i++; tokens.push({ op: "redir" }); continue; }
    if (c === "&" || c === "|") { push(); if (src[i + 1] === c || (c === "|" && src[i + 1] === "&")) i++; tokens.push({ op: c }); continue; }
    add(c);
  }
  push();
  return { tokens, nested };
}

// Groups tokens into simple commands (arrays of words); redirection targets are dropped.
function commands(tokens) {
  const out = [];
  let cur = [], skip = false;
  for (const t of tokens) {
    if (t.op === "redir") { skip = true; continue; }
    if (t.op || (!t.q && (t.w === "{" || t.w === "}"))) { out.push(cur); cur = []; skip = false; continue; }
    if (skip) { skip = false; continue; }
    cur.push(t.w);
  }
  out.push(cur);
  return out.filter((c) => c.length);
}

const progName = (w) => w.replace(/\\/g, "/").split("/").pop().toLowerCase().replace(/\.exe$/, "");

// A recursive-delete target is safe when it stays inside the project (or under /tmp) and some path
// segment is a build folder. Anything with variables, ~, braces, or a leading glob is unsafe.
function safeTarget(raw, cwd = "") {
  const t = raw.replace(/\\/g, "/");
  if (!t || /[$`{}%]/.test(t) || t.startsWith("~")) return false;
  const root = cwd.replace(/\\/g, "/").replace(/\/+$/, "");
  let rel;
  if (t.startsWith("/") || /^[a-z]:\//i.test(t)) {
    const abs = posix.normalize(t);
    if (/^\/tmp\/[^/*?[]/.test(abs)) return true;
    if (!root || !(abs.toLowerCase() + "/").startsWith(root.toLowerCase() + "/")) return false;
    rel = abs.slice(root.length + 1);
  } else rel = posix.normalize(t);
  if (!rel || rel === "." || rel === "./" || rel === ".." || rel.startsWith("../")) return false;
  let inSafe = false;
  for (const seg of rel.split("/").filter(Boolean)) {
    if (/[*?[]/.test(seg) && !inSafe) return false;
    if (SAFE_DIRS.has(seg)) inSafe = true;
  }
  return inSafe;
}

function psParam(flag) {
  const name = flag.replace(/^-/, "");
  return name ? PS_PARAMS.find((p) => p.startsWith(name)) ?? null : null;
}

// rm (bash and the PowerShell alias), Remove-Item and its aliases, and cmd's rd, rmdir, del, erase.
function checkDelete(name, args, cwd) {
  let recursive = false, endOpts = false;
  const targets = [];
  for (let k = 0; k < args.length; k++) {
    const a = args[k];
    if (!endOpts && a === "--") { endOpts = true; continue; }
    if (!endOpts && CMD_STYLE.has(name) && /^\/[a-z]$/i.test(a)) { if (/^\/s$/i.test(a)) recursive = true; continue; }
    if (!endOpts && a.startsWith("--")) { if (a === "--recursive") recursive = true; continue; }
    if (!endOpts && a.startsWith("-") && a.length > 1) {
      const [flag, val] = a.toLowerCase().split(/:(.*)/s);
      const p = psParam(flag);
      if (p === "recurse") { if (val === undefined || !/^\$?false$/.test(val)) recursive = true; continue; }
      if (p === "path" || p === "literalpath") { const v = val ?? args[++k]; if (v !== undefined) targets.push(v); continue; }
      if (p && PS_VALUED.has(p)) { if (val === undefined && args[k + 1] && !args[k + 1].startsWith("-")) k++; continue; }
      if (p) continue;
      if (/^-[a-z]+$/i.test(a) && /r/i.test(a)) recursive = true; // -rf, -Rf, -fr
      continue;
    }
    targets.push(a);
  }
  if (!recursive) return null;
  const list = targets.flatMap((t) => t.split(",")).filter(Boolean);
  if (!list.length) return "recursive delete with no visible target (piped input or a flag hid it)";
  const bad = list.filter((t) => !safeTarget(t, cwd));
  return bad.length ? `recursive delete of ${bad.join(", ")} (only ${[...SAFE_DIRS].join(", ")} inside the project, or /tmp, pass)` : null;
}

const WHOLE_TREE = /^(\.\/?|:\/?\.?|\*|:\(top\).*)$/;
const shortHas = (args, ch) => args.some((a) => /^-[a-zA-Z]+$/.test(a) && a.slice(1).includes(ch));

function checkGit(args) {
  let k = 0;
  while (k < args.length && args[k].startsWith("-")) { if (/^(-C|-c|--git-dir|--work-tree|--namespace)$/.test(args[k])) k++; k++; }
  const sub = args[k], rest = args.slice(k + 1);
  const pos = rest.filter((a) => !a.startsWith("-"));
  switch (sub) {
    case "push":
      if (rest.some((a) => /^--force(-with-lease|-if-includes)?(=|$)/.test(a)) || shortHas(rest, "f")) return "force push";
      if (pos.some((a) => a.startsWith("+"))) return "force push by +refspec";
      return null;
    case "reset": return rest.includes("--hard") ? "git reset --hard" : null;
    case "clean": return shortHas(rest, "f") || rest.includes("--force") ? "git clean -f" : null;
    case "branch": {
      const del = rest.includes("--delete") || shortHas(rest, "d"), force = rest.includes("--force") || shortHas(rest, "f");
      return shortHas(rest, "D") || (del && force) ? "git branch -D" : null;
    }
    case "checkout":
      if (rest.includes("-f") || rest.includes("--force")) return "git checkout --force (discards changes)";
      return pos.some((a) => WHOLE_TREE.test(a)) ? "git checkout . (discards all changes)" : null;
    case "restore": {
      const staged = rest.includes("--staged") || shortHas(rest, "S"), worktree = rest.includes("--worktree") || shortHas(rest, "W");
      if (staged && !worktree) return null; // unstaging only; the files stay as they are
      return pos.some((a) => WHOLE_TREE.test(a)) ? "git restore . (discards all changes)" : null;
    }
    case "stash": return pos[0] === "drop" || pos[0] === "clear" ? `git stash ${pos[0]}` : null;
    default: return null;
  }
}

function checkFind(args, cwd, shell, depth) {
  const starts = [];
  for (const a of args) { if (/^[-(!]/.test(a)) break; starts.push(a); }
  const roots = starts.length ? starts : ["."];
  if (args.includes("-delete") && roots.some((s) => !safeTarget(s, cwd))) return "find -delete outside build folders";
  for (let k = 0; k < args.length; k++) {
    if (!/^-(exec|execdir|ok|okdir)$/.test(args[k])) continue;
    const sub = [];
    for (k++; k < args.length && args[k] !== ";" && args[k] !== "+"; k++) sub.push(args[k]);
    for (const r of roots) {
      const hit = checkCommand(sub.map((w) => (w === "{}" ? `${r}/x` : w)), cwd, shell, depth);
      if (hit) return `find -exec: ${hit}`;
    }
  }
  return null;
}

function checkCommand(ws, cwd, shell, depth) {
  let i = 0;
  while (i < ws.length) {
    const w = ws[i], p = progName(w);
    if (/^[A-Za-z_][A-Za-z0-9_]*=/.test(w) || SHELL_KEYWORDS.has(p)) { i++; continue; }
    if (["sudo", "doas", "nohup", "command", "exec", "nice", "builtin"].includes(p)) {
      i++;
      while (i < ws.length && ws[i].startsWith("-")) { if (/^-[ugpCDrtUn]$/.test(ws[i])) i++; i++; }
      continue;
    }
    if (p === "env") { i++; while (i < ws.length && (ws[i].startsWith("-") || /^[A-Za-z_]\w*=/.test(ws[i]))) i++; continue; }
    if (p === "xargs") { i++; while (i < ws.length && ws[i].startsWith("-")) { if (/^-[IdLnPsE]$/.test(ws[i])) i++; i++; } continue; }
    break;
  }
  if (i >= ws.length) return null;
  const name = progName(ws[i]), args = ws.slice(i + 1);

  if (["bash", "sh", "zsh", "dash", "ksh"].includes(name)) {
    const c = args.findIndex((a) => /^-[a-z]*c[a-z]*$/.test(a));
    return c !== -1 && args[c + 1] !== undefined ? scan(args[c + 1], "bash", cwd, depth + 1) : null;
  }
  if (name === "powershell" || name === "pwsh") {
    const c = args.findIndex((a) => /^-c(o(m(m(a(n(d)?)?)?)?)?)?$/i.test(a));
    return c !== -1 ? scan(args.slice(c + 1).join(" "), "powershell", cwd, depth + 1) : null;
  }
  if (name === "cmd") {
    const c = args.findIndex((a) => /^\/[ck]$/i.test(a));
    return c !== -1 ? scan(args.slice(c + 1).join(" "), "cmd", cwd, depth + 1) : null;
  }
  if (name === "eval") return scan(args.join(" "), "bash", cwd, depth + 1);
  if (name === "invoke-expression" || name === "iex") return scan(args.join(" "), "powershell", cwd, depth + 1);
  if (name === "git") return checkGit(args);
  if (name === "find") return checkFind(args, cwd, shell, depth);
  if (DELETE_CMDS.has(name)) return checkDelete(name, args, cwd);
  return null;
}

// Returns a short label for the first destructive command found, or null.
function scan(src, shell = "bash", cwd = "", depth = 0) {
  if (depth > 4) return null;
  const { tokens, nested } = tokenize(String(src), shell);
  for (const body of nested) { const hit = scan(body, shell, cwd, depth + 1); if (hit) return hit; }
  for (const ws of commands(tokens)) { const hit = checkCommand(ws, cwd, shell, depth); if (hit) return hit; }
  return null;
}

let raw = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (c) => (raw += c));
process.stdin.on("end", () => {
  let input;
  try { input = JSON.parse(raw); } catch {
    process.stderr.write("crunchless guard: could not read the hook payload, so the command was blocked. Remove the guard-bash hook from .claude/settings.json if this persists.\n");
    process.exit(2);
  }
  const cmd = input?.tool_input?.command;
  if (typeof cmd !== "string" || !cmd) process.exit(0);
  const shell = input.tool_name === "PowerShell" ? "powershell" : "bash";
  const hit = scan(cmd, shell, input.cwd || process.cwd());
  if (hit) {
    process.stderr.write(`crunchless guard: blocked ${hit}. This hook is a tripwire for common accidents; if the command is intended, ask the user to run it themselves.\n`);
    process.exit(2);
  }
  process.exit(0);
});
